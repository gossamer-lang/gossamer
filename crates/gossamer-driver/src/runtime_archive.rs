//! The runtime a program built with `--frame-pointers` links: this
//! toolchain's runtime compiled from the sources it carries, with frame
//! pointers, once per target, and kept in the bindings cache beside those
//! sources.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use thiserror::Error;

use crate::archive_flags::{FRAME_POINTER_RUSTFLAGS, program_archive_rustflags};
use crate::binding_build::{
    AdvisoryLock, BindingBuildError, CargoBuild, Profile, TOOLCHAIN_LOCK, TOOLCHAIN_SOURCE_DIGEST,
    build_lock_path, cache_root, compiler_identity, link_archive_exception_tables, run_cargo_build,
    seed_lockfile, toml_path_kv, toolchain_source_root, write_if_different,
};

/// Errors raised building the runtime with frame pointers.
#[derive(Debug, Error)]
pub enum RuntimeArchiveError {
    /// `cargo` was not found on PATH.
    #[error(
        "`--frame-pointers` builds the runtime from source; install Rust + cargo from https://rustup.rs"
    )]
    CargoMissing,
    /// `cargo build` exited unsuccessfully; its diagnostics were streamed to
    /// the terminal as it ran.
    #[error("building the runtime with frame pointers: {0}")]
    Build(BindingBuildError),
    /// I/O error while preparing the cache.
    #[error("runtime cache i/o error: {0}")]
    Io(#[from] io::Error),
}

impl From<BindingBuildError> for RuntimeArchiveError {
    fn from(err: BindingBuildError) -> Self {
        match err {
            BindingBuildError::CargoMissing => Self::CargoMissing,
            BindingBuildError::Io(err) => Self::Io(err),
            other => Self::Build(other),
        }
    }
}

/// The archive of this toolchain's runtime built with frame pointers for
/// `target` (the host when `None`), with the runtime crate's `features`.
/// The first use builds it; later ones answer the cached archive.
///
/// # Errors
///
/// `cargo` is missing, the build fails, or the cache cannot be written.
pub fn frame_pointer_runtime(
    target: Option<&str>,
    features: &[&str],
) -> Result<PathBuf, RuntimeArchiveError> {
    frame_pointer_runtime_in(&cache_root()?, target, features)
}

fn frame_pointer_runtime_in(
    cache_root: &Path,
    target: Option<&str>,
    features: &[&str],
) -> Result<PathBuf, RuntimeArchiveError> {
    let workdir = cache_root.join("bindings").join(format!(
        "runtime-frame-pointers-{}-{}",
        env!("CARGO_PKG_VERSION"),
        &TOOLCHAIN_SOURCE_DIGEST[..16]
    ));
    crate::cache_maintenance::hold_in_use(&workdir)?;
    let _lock = AdvisoryLock::acquire(
        &build_lock_path(&workdir),
        "the runtime with frame pointers",
    )?;
    let cargo_toml = workdir.join("Cargo.toml");
    write_if_different(&cargo_toml, &manifest(features)?)?;
    write_if_different(&workdir.join("lib.rs"), LIB_RS)?;
    seed_lockfile(&workdir, TOOLCHAIN_LOCK, "")?;

    let archive = archive_path(&workdir, target);
    let flags = rustflags(target);
    let stamp_path = archive.with_file_name("frame-pointers.stamp");
    let stamp = format!(
        "{}\n{}\n{}",
        TOOLCHAIN_SOURCE_DIGEST,
        compiler_identity(&workdir),
        flags.join(" ")
    );
    if archive.exists() && fs::read_to_string(&stamp_path).is_ok_and(|seen| seen == stamp) {
        return Ok(archive);
    }
    run_cargo_build(
        &CargoBuild {
            manifest_path: &cargo_toml,
            target_dir: &workdir.join("target"),
            profile: Profile::Release,
            cargo_target: target,
            target_args: &["--lib"],
            crate_label: "gossamer-runtime",
            rustc_args: &[],
            rustflags: &flags,
        },
        None,
    )?;
    link_archive_exception_tables(&archive)?;
    fs::write(&stamp_path, stamp)?;
    Ok(archive)
}

/// The generated crate: a staticlib of the runtime and everything it links,
/// optimised as the toolchain's own archive is.
fn manifest(features: &[&str]) -> io::Result<String> {
    let root = toolchain_source_root()?;
    let features: Vec<String> = features.iter().map(|f| format!("{f:?}")).collect();
    Ok(format!(
        r#"# generated by gos build -- this toolchain's runtime with frame pointers
[package]
name = "gos-runtime-frame-pointers"
version = "0.0.0"
edition = "2024"
publish = false

# A workspace of its own, so a cache under some other workspace's tree is
# not absorbed into it.
[workspace]

[lib]
name = "gos_runtime_frame_pointers"
crate-type = ["staticlib"]
path = "lib.rs"

[dependencies]
gossamer-runtime = {{ {path}, features = [{features}] }}

[profile.release]
lto = "fat"
codegen-units = 1
debug = false
incremental = false

[profile.release.build-override]
strip = false
"#,
        path = toml_path_kv("path", &root.join("crates").join("gossamer-runtime")),
        features = features.join(", "),
    ))
}

const LIB_RS: &str = "// generated by gos build\nextern crate gossamer_runtime;\n";

/// Where Cargo lands the archive for `target`.
fn archive_path(workdir: &Path, target: Option<&str>) -> PathBuf {
    let mut dir = workdir.join("target");
    if let Some(t) = target {
        dir = dir.join(t);
    }
    let name = if cfg!(all(windows, target_env = "msvc")) {
        "gos_runtime_frame_pointers.lib"
    } else {
        "libgos_runtime_frame_pointers.a"
    };
    dir.join(Profile::Release.dir()).join(name)
}

/// The toolchain archive's flags for `target`, with frame pointers, as the
/// separate arguments Cargo takes them in.
fn rustflags(target: Option<&str>) -> Vec<&'static str> {
    let arch = target
        .and_then(|t| t.split('-').next())
        .unwrap_or(std::env::consts::ARCH);
    let musl = target.is_some_and(|t| t.ends_with("-linux-musl"));
    program_archive_rustflags(true, arch, musl)
        .into_iter()
        .chain(FRAME_POINTER_RUSTFLAGS.iter().copied())
        .flat_map(str::split_whitespace)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_static_musl_runtime_keeps_the_archive_flags_and_adds_frame_pointers() {
        let flags = rustflags(Some("x86_64-unknown-linux-musl"));
        for flag in [
            "--cfg",
            "gos_program_archive",
            "gos_frame_pointers",
            "force-frame-pointers=yes",
            "relocation-model=static",
            "llvm-args=-align-all-functions=6",
        ] {
            assert!(flags.contains(&flag), "{flag} missing from {flags:?}");
        }
        assert!(flags.iter().all(|flag| !flag.contains(' ')), "{flags:?}");
    }

    #[test]
    fn a_host_runtime_is_not_built_for_a_fixed_address() {
        let flags = rustflags(None);
        assert!(flags.contains(&"force-frame-pointers=yes"), "{flags:?}");
        assert!(!flags.contains(&"relocation-model=static"), "{flags:?}");
    }

    #[test]
    fn the_generated_crate_asks_for_the_runtime_features() {
        let text = manifest(&["inline-vec-words-8"]).expect("toolchain sources unpack");
        assert!(
            text.contains(r#"features = ["inline-vec-words-8"]"#),
            "{text}"
        );
        assert!(text.contains(r#"crate-type = ["staticlib"]"#), "{text}");
    }

    #[test]
    fn the_archive_lands_under_the_target_triple() {
        let dir = Path::new("/cache/w");
        let path = archive_path(dir, Some("x86_64-unknown-linux-musl"));
        assert!(
            path.starts_with("/cache/w/target/x86_64-unknown-linux-musl/release"),
            "{path:?}"
        );
    }
}
