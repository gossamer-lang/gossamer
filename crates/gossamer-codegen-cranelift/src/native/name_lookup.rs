pub(super) fn name_to_static(name: &str, set: &[&'static str]) -> Option<&'static str> {
    for s in set {
        if *s == name {
            return Some(*s);
        }
    }
    None
}

/// The canonical `&'static str` for a runtime symbol the generic call
/// lowering may reference, or `None` for a name no runtime declares.
///
/// The ABI registry owns that string for every `gos_rt_*` symbol, so the
/// answer is a registry lookup. The three aliases below are the only
/// names MIR spells that no runtime symbol carries: an unchecked
/// element accessor lowers to the same helper as the checked one (the
/// bounds check is elided in MIR, not in the callee), and a weak
/// upgrade's payload is read with the ordinary carrier accessor.
pub(super) fn generic_rt_static_name(name: &str) -> Option<&'static str> {
    match name {
        "gos_rt_vec_get_i64_unchecked" => Some("gos_rt_vec_get_i64"),
        "gos_rt_vec_set_i64_unchecked" => Some("gos_rt_vec_set_i64"),
        "gos_rt_weak_opt_payload" => Some("gos_rt_result_payload"),
        _ => gossamer_abi::lookup(name).map(|entry| entry.name),
    }
}
