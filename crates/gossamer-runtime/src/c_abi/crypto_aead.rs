/// `crypto::ed25519::keypair() -> Result<([u8], [u8]), errors::Error>`
/// - fresh Ed25519 keypair `(secret, public)` from the OS CSPRNG.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gos_rt_crypto_ed25519_keypair() -> i128 {
    ffi_entry!(0i128, {
        use ed25519_dalek::SigningKey;
        let mut seed = [0u8; 32];
        if getrandom::fill(&mut seed).is_err() {
            return aead_err("ed25519: rng failure");
        }
        let signing = SigningKey::from_bytes(&seed);
        let public = signing.verifying_key();
        let secret_vec = bytes_to_gosvec(&signing.to_bytes()) as i64;
        let public_vec = bytes_to_gosvec(&public.to_bytes()) as i64;
        let pair = crate::c_abi::rc::counted_words(&[secret_vec, public_vec], &KEYPAIR_VECS_META);
        super::vec::gos_rt_result_new(0, pair as i64)
    })
}

/// `crypto::ed25519::sign(secret, message)
/// -> Result<[u8], errors::Error>` - 64-byte detached signature.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gos_rt_crypto_ed25519_sign(
    secret: *const GosVec,
    message: *const GosVec,
) -> i128 {
    ffi_entry!(0i128, {
        use ed25519_dalek::{Signer, SigningKey};
        let secret = unsafe { gosvec_u8(secret) };
        let msg = unsafe { gosvec_u8(message) };
        let secret: [u8; 32] = match secret.as_slice().try_into() {
            Ok(s) => s,
            Err(_) => return aead_err("ed25519: secret must be 32 bytes"),
        };
        let signing = SigningKey::from_bytes(&secret);
        let sig = signing.sign(&msg).to_bytes();
        super::vec::gos_rt_result_new(0, bytes_to_gosvec(&sig) as i64)
    })
}

/// `crypto::ed25519::verify(public, message, signature)
/// -> Result<(), errors::Error>` - `Ok(())` on a valid signature,
/// `Err` otherwise. Matches the VM's `ok_variant(Value::Unit)`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gos_rt_crypto_ed25519_verify(
    public: *const GosVec,
    message: *const GosVec,
    signature: *const GosVec,
) -> i128 {
    ffi_entry!(0i128, {
        use ed25519_dalek::{Signature, Verifier, VerifyingKey};
        let public = unsafe { gosvec_u8(public) };
        let msg = unsafe { gosvec_u8(message) };
        let sig = unsafe { gosvec_u8(signature) };
        let public: [u8; 32] = match public.as_slice().try_into() {
            Ok(p) => p,
            Err(_) => return aead_err("ed25519: public key must be 32 bytes"),
        };
        let sig: [u8; 64] = match sig.as_slice().try_into() {
            Ok(s) => s,
            Err(_) => return aead_err("ed25519: signature must be 64 bytes"),
        };
        let key = match VerifyingKey::from_bytes(&public) {
            Ok(k) => k,
            Err(e) => return aead_err(&format!("ed25519: public key: {e}")),
        };
        match key.verify(&msg, &Signature::from_bytes(&sig)) {
            Ok(()) => super::vec::gos_rt_result_new(0, 0),
            Err(e) => aead_err(&format!("ed25519: verify: {e}")),
        }
    })
}
